/// Atlas layout: 16 columns of glyph cells.
///
/// Each cell carries a one-texel transparent gutter. Without it, bilinear
/// filtering at the large sizes the interface uses drags a sliver of the
/// neighbouring glyph into view, which shows up as stray marks beside letters.
pub const ATLAS_COLS: usize = 16;
pub const ATLAS_ROWS: usize = (GLYPH_COUNT + ATLAS_COLS - 1) / ATLAS_COLS;
pub const GUTTER: usize = 1;
pub const CELL_W: usize = GLYPH_W + GUTTER * 2;
pub const CELL_H: usize = GLYPH_H + GUTTER * 2;
pub const ATLAS_W: usize = ATLAS_COLS * CELL_W;
pub const ATLAS_H: usize = ATLAS_ROWS * CELL_H;

/// A rasterised font ready for upload.
pub struct FontAtlas {
    /// Single-channel coverage, `ATLAS_W * ATLAS_H`.
    pub pixels: Vec<u8>,
    /// Advance width in pixels for each glyph, measured from its ink.
    pub advance: [u8; GLYPH_COUNT],
    /// Leftmost inked column, so glyphs can be drawn tightly.
    pub bearing: [u8; GLYPH_COUNT],
}

impl FontAtlas {
    pub fn build() -> FontAtlas {
        let mut pixels = vec![0u8; ATLAS_W * ATLAS_H];
        let mut advance = [0u8; GLYPH_COUNT];
        let mut bearing = [0u8; GLYPH_COUNT];

        for g in 0..GLYPH_COUNT {
            let cx = (g % ATLAS_COLS) * CELL_W + GUTTER;
            let cy = (g / ATLAS_COLS) * CELL_H + GUTTER;
            let mut min_x = GLYPH_W;
            let mut max_x = 0usize;

            for row in 0..GLYPH_H {
                let bits = GLYPHS[g * GLYPH_H + row];
                for col in 0..GLYPH_W {
                    if bits & (0x80 >> col) != 0 {
                        pixels[(cy + row) * ATLAS_W + cx + col] = 255;
                        if col < min_x { min_x = col; }
                        if col > max_x { max_x = col; }
                    }
                }
            }

            if min_x > max_x {
                // Blank glyph: give the space a sensible width.
                advance[g] = 4;
                bearing[g] = 0;
            } else {
                bearing[g] = min_x as u8;
                advance[g] = (max_x - min_x + 2) as u8;
            }
        }

        FontAtlas { pixels, advance, bearing }
    }

    #[inline]
    pub fn index_of(c: char) -> usize {
        let b = c as u32;
        if b < FIRST_CHAR as u32 || b > LAST_CHAR as u32 {
            // Anything we cannot draw becomes a small block, which is more
            // useful than silently vanishing.
            ('?' as u32 - FIRST_CHAR as u32) as usize
        } else {
            (b - FIRST_CHAR as u32) as usize
        }
    }

    /// UV rectangle of a glyph within the atlas, in 0..1.
    #[inline]
    pub fn uv(index: usize) -> [f32; 4] {
        let cx = (index % ATLAS_COLS) * CELL_W + GUTTER;
        let cy = (index / ATLAS_COLS) * CELL_H + GUTTER;
        [
            cx as f32 / ATLAS_W as f32,
            cy as f32 / ATLAS_H as f32,
            GLYPH_W as f32 / ATLAS_W as f32,
            GLYPH_H as f32 / ATLAS_H as f32,
        ]
    }

    /// Width of a string in pixels at scale 1, including inter-letter spacing.
    pub fn measure(&self, text: &str, tracking: f32) -> f32 {
        let mut w = 0.0f32;
        for c in text.chars() {
            let i = FontAtlas::index_of(c);
            w += self.advance[i] as f32 + tracking;
        }
        (w - tracking).max(0.0)
    }
}
